import React, { useEffect, useState } from 'react';
import { FileDown, FileSpreadsheet } from 'lucide-react';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';
import type { AuthUser } from '../../shared/types';
import { apiFetch } from '../lib/api';

interface ReportsModuleProps {
  user: AuthUser;
  activeOption?: string | null;
  onSelectOption?: (opt: string) => void;
}

const REPORT_TYPES = [
  { id: 'daily_leads', label: 'Daily Lead Report', referralAllowed: false },
  { id: 'monthly_leads', label: 'Monthly Lead Report', referralAllowed: false },
  { id: 'referral_leads', label: 'Referral-wise Lead Report', referralAllowed: true },
  { id: 'employee_leads', label: 'Employee-wise Lead Report', referralAllowed: false },
  { id: 'field_officer_performance', label: 'Field Officer Performance', referralAllowed: false },
  { id: 'branch_performance', label: 'Branch Performance', referralAllowed: false },
  { id: 'case_status', label: 'Case Status Report', referralAllowed: true },
  { id: 'disbursement', label: 'Disbursement Report', referralAllowed: false },
  { id: 'pending_followup', label: 'Pending Follow-up Report', referralAllowed: false },
  { id: 'duplicate_verification', label: 'Duplicate Verification Report', referralAllowed: false },
  { id: 'enquiry', label: 'Enquiry Report', referralAllowed: true },
  { id: 'penalty', label: 'Penalty Report', referralAllowed: false },
  { id: 'gps_visit', label: 'GPS Visit Report', referralAllowed: false },
  { id: 'bike_run', label: 'Daily / Weekly / Monthly Bike Run Report', referralAllowed: false },
  { id: 'petrol_incentive', label: 'Petrol Incentive Report', referralAllowed: false },
  { id: 'attendance', label: 'Daily Self-Attendance & Late Penalty Report', referralAllowed: false },
  { id: 'leave', label: 'Leave & Seniority Approval Penalty Report', referralAllowed: false },
];

export const ReportsModule: React.FC<ReportsModuleProps> = ({
  user,
  activeOption,
  onSelectOption,
}) => {
  const availableReports =
    user.role === 'REFERRAL_PARTNER'
      ? REPORT_TYPES.filter((r) => r.referralAllowed)
      : REPORT_TYPES;

  const initialReportId =
    activeOption && availableReports.some((r) => r.id === activeOption)
      ? activeOption
      : availableReports[0].id;
  const [selectedType, setSelectedType] = useState(initialReportId);

  useEffect(() => {
    if (activeOption && availableReports.some((r) => r.id === activeOption)) {
      setSelectedType(activeOption);
    } else if (activeOption === null) {
      setSelectedType(availableReports[0].id);
    }
  }, [activeOption]);
  const [reportData, setReportData] = useState<{
    title: string;
    columns: string[];
    rows: Record<string, unknown>[];
    generatedAt: string;
  } | null>(null);
  const [loading, setLoading] = useState(true);

  const loadReport = async (type: string) => {
    setLoading(true);
    try {
      const res = await apiFetch<any>(`/reports/${type}`);
      setReportData(res);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadReport(selectedType);
  }, [selectedType]);

  const exportPdf = () => {
    if (!reportData) return;
    const doc = new jsPDF({ orientation: 'landscape' });
    doc.setFontSize(14);
    doc.text(`AMBIKA ASSOCIATE — ${reportData.title}`, 14, 15);
    doc.setFontSize(9);
    doc.text(`Generated by: ${user.fullName} (${user.employeeCode}) · ${reportData.generatedAt}`, 14, 22);

    const body = reportData.rows.map((r) =>
      reportData.columns.map((c) => String(r[c] ?? '—'))
    );

    autoTable(doc, {
      head: [reportData.columns],
      body,
      startY: 27,
      styles: { fontSize: 8 },
      headStyles: { fillColor: [15, 39, 68] },
    });

    doc.save(`ambika_${selectedType}_${new Date().toISOString().slice(0, 10)}.pdf`);
  };

  const exportExcel = () => {
    if (!reportData) return;
    const ws = XLSX.utils.json_to_sheet(
      reportData.rows.length > 0 ? reportData.rows : [Object.fromEntries(reportData.columns.map((c) => [c, '']))]
    );
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, reportData.title.slice(0, 30));
    XLSX.writeFile(wb, `ambika_${selectedType}_${new Date().toISOString().slice(0, 10)}.xlsx`);
  };

  return (
    <div className="space-y-5">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-xl font-display font-bold text-[#0F2744]">Reports &amp; Analytics</h1>
          <p className="text-xs text-slate-500 mt-0.5">
            Live database reports with role-scoped visibility, PDF export, and Excel (.xlsx) download.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            type="button"
            disabled={!reportData || loading}
            onClick={exportPdf}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-[#0F2744] hover:bg-[#16365D] text-white text-xs font-semibold disabled:opacity-50 whitespace-nowrap"
          >
            <FileDown className="w-4 h-4" />
            Export PDF
          </button>
          <button
            type="button"
            disabled={!reportData || loading}
            onClick={exportExcel}
            className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-[#15803D] hover:bg-green-800 text-white text-xs font-semibold disabled:opacity-50 whitespace-nowrap"
          >
            <FileSpreadsheet className="w-4 h-4" />
            Export Excel
          </button>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5 items-start">
        <div className="lg:col-span-3 bg-white border border-slate-200 rounded-xl p-2 divide-y divide-slate-100">
          {availableReports.map((r) => (
            <button
              key={r.id}
              type="button"
              onClick={() => {
                setSelectedType(r.id);
                onSelectOption?.(r.id);
              }}
              className={`w-full text-left px-3 py-2.5 text-xs font-medium rounded-lg transition-colors ${
                selectedType === r.id
                  ? 'bg-[#0F2744] text-white font-semibold'
                  : 'text-slate-700 hover:bg-slate-50'
              }`}
            >
              {r.label}
            </button>
          ))}
        </div>

        <div className="lg:col-span-9 bg-white border border-slate-200 rounded-xl overflow-hidden">
          <div className="px-5 py-3.5 border-b border-slate-200 flex items-center justify-between gap-4">
            <h2 className="text-sm font-display font-bold text-[#0F2744]">
              {reportData?.title || 'Loading...'}
            </h2>
            <span className="text-xs text-slate-500 tabular-nums">
              {reportData ? `${reportData.rows.length} rows` : ''}
            </span>
          </div>
          <div className="overflow-x-auto">
            {loading || !reportData ? (
              <div className="p-10 text-center text-xs text-slate-500">Generating report...</div>
            ) : (
              <table className="w-full text-xs">
                <thead className="bg-slate-50 text-slate-500 border-b border-slate-200">
                  <tr>
                    {reportData.columns.map((col) => (
                      <th key={col} className="text-left px-4 py-2.5 font-semibold whitespace-nowrap">
                        {col}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {reportData.rows.map((row, idx) => (
                    <tr key={idx} className="hover:bg-slate-50">
                      {reportData.columns.map((col) => (
                        <td key={col} className="px-4 py-2.5 text-slate-700 whitespace-nowrap font-mono tabular-nums">
                          {String(row[col] ?? '—')}
                        </td>
                      ))}
                    </tr>
                  ))}
                  {reportData.rows.length === 0 && (
                    <tr>
                      <td colSpan={reportData.columns.length} className="px-4 py-10 text-center text-slate-500">
                        No records found for this report.
                      </td>
                    </tr>
                  )}
                </tbody>
              </table>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
